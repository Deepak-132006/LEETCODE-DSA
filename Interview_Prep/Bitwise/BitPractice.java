package Interview_Prep.Bitwise;

public class BitPractice {
    public static void main(String[] args) {
        int a = 12;
        int b = 10;

        int and = a & b;
        int or = a | b;
        int xor = a ^ b;

        System.out.println(and);
        System.out.println(or);
        System.out.println(xor);
    }
}
